// richConfig exercises every generator knob.
func richConfig(seed uint64, names NameStyle, weights WeightDist) GenConfig {
	return GenConfig{
		Seed:            seed,
		NumTransactions: 300,
		NumItems:        30,
		MinLen:          0,
		MaxLen:          8,
		Skew:            1,
		Patterns:        4,
		PatternLen:      3,
		PatternProb:     0.3,
		DupItemProb:     0.05,
		DupTxProb:       0.1,
		EmptyProb:       0.05,
		Weights:         weights,
		Names:           names,
	}
}

// generateTable generates a dataset and serializes it.
func generateTable(t testing.TB, cfg GenConfig, weighted bool) []byte {
	t.Helper()
	txs, err := Generate(cfg)
	if err != nil {
		t.Fatalf("Generate(%+v): %v", cfg, err)
	}
	var buf bytes.Buffer
	if err := WriteTable(&buf, txs, weighted); err != nil {
		t.Fatalf("WriteTable: %v", err)
	}
	return buf.Bytes()
}

func TestGenerate_deterministic(t *testing.T) {
	t.Parallel()
	for _, names := range []NameStyle{NamesLetters, NamesNumbers, NamesUnicode, NamesHash, NamesSeparators} {
		cfg := richConfig(7, names, WeightsSmall)
		first, second := generateTable(t, cfg, true), generateTable(t, cfg, true)
		if !bytes.Equal(first, second) {
			t.Errorf("names %d: same seed, different bytes", names)
		}
		cfg.Seed = 8
		if bytes.Equal(first, generateTable(t, cfg, true)) {
			t.Errorf("names %d: seeds 7 and 8 give the same bytes", names)
		}
	}
}

// TestGenerate_golden pins the generated bytes. A change means that
// datasets generated from recorded seeds (e.g. in failure reports or
// fixtures) no longer reproduce; only change it deliberately.
func TestGenerate_golden(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name     string
		cfg      GenConfig
		weighted bool
		expected string // SHA-256 of the WriteTable output
	}{
		{
			name:     "letters unit weights",
			cfg:      richConfig(1, NamesLetters, WeightsUnit),
			expected: "cadf469f385356855d4f6cf281607bdc2c975d8cee53ce38eef608835d420451",
		},
		{
			name:     "unicode zero weights",
			cfg:      richConfig(2, NamesUnicode, WeightsWithZero),
			weighted: true,
			expected: "4bc5b50abbde288d61bc5b2bddfbb48cc229eb7737de380f89e66b9612d89894",
		},
		{
			name:     "numbers large weights skew 3",
			cfg:      func() GenConfig { c := richConfig(3, NamesNumbers, WeightsLarge); c.Skew = 3; return c }(),
			weighted: true,
			expected: "a450dabb6052da3eda7e7e4ed9cfae21646ff4a27f000f02aa377ff4c3e563b5",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			sum := sha256.Sum256(generateTable(t, tt.cfg, tt.weighted))
			if got := hex.EncodeToString(sum[:]); got != tt.expected {
				t.Errorf("SHA-256 = %s, want %s", got, tt.expected)
			}
		})
	}
}

func TestGenerate_knobs(t *testing.T) {
	t.Parallel()
	base := GenConfig{Seed: 3, NumTransactions: 200, NumItems: 6, MinLen: 1, MaxLen: 4}
	tests := []struct {
		name   string
		modify func(c *GenConfig)
		check  func(t *testing.T, txs []Transaction)
	}{
		{
			name:   "empty transactions",
			modify: func(c *GenConfig) { c.EmptyProb = 1 },
			check: func(t *testing.T, txs []Transaction) {
				for _, tx := range txs {
					if tx.Items == nil || len(tx.Items) != 0 {
						t.Fatalf("transaction %q, want empty and non-nil", tx.Items)
					}
				}
			},
		},
		{
			name:   "fixed length without duplicates",
			modify: func(c *GenConfig) { c.MinLen, c.MaxLen = 3, 3 },
			check: func(t *testing.T, txs []Transaction) {
				for _, tx := range txs {
					if len(tx.Items) != 3 || len(NewItemSet(tx.Items...)) != 3 {
						t.Fatalf("transaction %q, want 3 distinct items", tx.Items)
					}
				}
			},
		},
		{
			name:   "length capped by alphabet",
			modify: func(c *GenConfig) { c.MinLen, c.MaxLen = 10, 10 },
			check: func(t *testing.T, txs []Transaction) {
				for _, tx := range txs {
					if len(tx.Items) != 6 {
						t.Fatalf("transaction %q, want all 6 items", tx.Items)
					}
				}
			},
		},
		{
			name:   "length range",
			modify: func(c *GenConfig) { c.MinLen, c.MaxLen = 2, 4 },
			check: func(t *testing.T, txs []Transaction) {
				seen := map[int]bool{}
				for _, tx := range txs {
					if n := len(tx.Items); n < 2 || n > 4 {
						t.Fatalf("transaction %q, want 2..4 items", tx.Items)
					}
					seen[len(tx.Items)] = true
				}
				if len(seen) != 3 {
					t.Errorf("lengths %v, want 2, 3 and 4", seen)
				}
			},
		},
		{
			name:   "duplicate items",
			modify: func(c *GenConfig) { c.DupItemProb = 1 },
			check: func(t *testing.T, txs []Transaction) {
				for _, tx := range txs {
					counts := map[string]int{}
					for _, item := range tx.Items {
						counts[item]++
					}
					for item, n := range counts {
						if n != 2 {
							t.Fatalf("transaction %q has %q %d times, want 2", tx.Items, item, n)
						}
					}
				}
			},
		},
		{
			name: "planted pattern",
			modify: func(c *GenConfig) {
				c.MinLen, c.MaxLen = 0, 0
				c.Patterns, c.PatternLen, c.PatternProb = 1, 3, 1
			},
			check: func(t *testing.T, txs []Transaction) {
				first := NewItemSet(txs[0].Items...)
				for _, tx := range txs {
					if !NewItemSet(tx.Items...).Equal(first) || len(first) != 3 {
						t.Fatalf("transaction %q, want the pattern %v", tx.Items, first)
					}
				}
			},
		},
		{
			name:   "duplicate transactions",
			modify: func(c *GenConfig) { c.DupTxProb = 1 },
			check: func(t *testing.T, txs []Transaction) {
				first := NewItemSet(txs[0].Items...)
				shuffled := false
				for _, tx := range txs {
					if !NewItemSet(tx.Items...).Equal(first) {
						t.Fatalf("transaction %q, want a copy of %q", tx.Items, txs[0].Items)
					}
					shuffled = shuffled || !slices.Equal(tx.Items, txs[0].Items)
				}
				if len(first) > 2 && !shuffled {
					t.Error("copies are never shuffled")
				}
			},
		},
		{
			name:   "skew",
			modify: func(c *GenConfig) { c.Skew = 2; c.MinLen, c.MaxLen = 1, 1 },
			check: func(t *testing.T, txs []Transaction) {
				counts := map[string]int{}
				for _, tx := range txs {
					counts[tx.Items[0]]++
				}
				if counts["a"] <= 4*counts["f"] {
					t.Errorf("counts %v: item a should be far more popular than f", counts)
				}
			},
		},
		{name: "unit weights", modify: func(*GenConfig) {}, check: weightRange(1, 1, true)},
		{name: "small weights", modify: func(c *GenConfig) { c.Weights = WeightsSmall }, check: weightRange(1, 5, true)},
		{name: "small weights max 2", modify: func(c *GenConfig) { c.Weights, c.MaxWeight = WeightsSmall, 2 }, check: weightRange(1, 2, true)},
		{name: "weights with zero", modify: func(c *GenConfig) { c.Weights = WeightsWithZero }, check: weightRange(0, 3, true)},
		{name: "large weights", modify: func(c *GenConfig) { c.Weights = WeightsLarge }, check: weightRange(1<<19, 1<<20, false)},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			cfg := base
			tt.modify(&cfg)
			txs, err := Generate(cfg)
			if err != nil {
				t.Fatalf("Generate: %v", err)
			}
			if len(txs) != cfg.NumTransactions {
				t.Fatalf("%d transactions, want %d", len(txs), cfg.NumTransactions)
			}
			tt.check(t, txs)
		})
	}
}

// weightRange checks that all weights are in [lo, hi] and, with
// hitsBounds, that both bounds occur.
func weightRange(lo, hi tract.Supp, hitsBounds bool) func(t *testing.T, txs []Transaction) {
	return func(t *testing.T, txs []Transaction) {
		seen := map[tract.Supp]bool{}
		for _, tx := range txs {
			if tx.Weight < lo || tx.Weight > hi {
				t.Fatalf("weight %d outside [%d, %d]", tx.Weight, lo, hi)
			}
			seen[tx.Weight] = true
		}
		if hitsBounds && (!seen[lo] || !seen[hi]) {
			t.Errorf("weights %v do not reach both %d and %d", seen, lo, hi)
		}
	}
}

func TestGenerate_invalid(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name   string
		modify func(c *GenConfig)
	}{
		{name: "negative transactions", modify: func(c *GenConfig) { c.NumTransactions = -1 }},
		{name: "no items", modify: func(c *GenConfig) { c.NumItems = 0 }},
		{name: "negative length", modify: func(c *GenConfig) { c.MinLen = -1 }},
		{name: "length range", modify: func(c *GenConfig) { c.MinLen, c.MaxLen = 3, 2 }},
		{name: "skew", modify: func(c *GenConfig) { c.Skew = 9 }},
		{name: "pattern too long", modify: func(c *GenConfig) { c.Patterns, c.PatternLen = 1, 6 }},
		{name: "probability", modify: func(c *GenConfig) { c.DupTxProb = 1.5 }},
		{name: "name style", modify: func(c *GenConfig) { c.Names = NamesSeparators + 1 }},
		{name: "weight distribution", modify: func(c *GenConfig) { c.Weights = WeightsLarge + 1 }},
		{name: "negative max weight", modify: func(c *GenConfig) { c.Weights, c.MaxWeight = WeightsSmall, -1 }},
		{name: "total above int32", modify: func(c *GenConfig) { c.Weights, c.MaxWeight = WeightsLarge, 1<<30 }},
		{name: "total above max total", modify: func(c *GenConfig) { c.Weights, c.MaxTotal = WeightsSmall, 99 }},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			cfg := GenConfig{NumTransactions: 20, NumItems: 5, MaxLen: 3}
			tt.modify(&cfg)
			if _, err := Generate(cfg); err == nil {
				t.Errorf("Generate(%+v) succeeded, want an error", cfg)
			}
		})
	}

	// A larger MaxTotal admits weights beyond the C reference's range.
	cfg := GenConfig{NumTransactions: 20, NumItems: 5, MaxLen: 3, Weights: WeightsLarge, MaxWeight: 1 << 40, MaxTotal: 1 << 50}
	if _, err := Generate(cfg); err != nil {
		t.Errorf("Generate with MaxTotal 2^50: %v", err)
	}
}

func TestNameStyle_itemName(t *testing.T) {
	t.Parallel()
	examples := []struct {
		style    NameStyle
		i        int
		expected string
	}{
		{NamesLetters, 0, "a"}, {NamesLetters, 25, "z"}, {NamesLetters, 26, "aa"},
		{NamesLetters, 701, "zz"}, {NamesLetters, 702, "aaa"},
		{NamesNumbers, 0, "0"}, {NamesNumbers, 10, "10"},
		{NamesUnicode, 0, "α"}, {NamesUnicode, 1, "xа"}, {NamesUnicode, 2, "一"}, {NamesUnicode, 3, "x😀"},
		{NamesUnicode, 4, "β"}, {NamesUnicode, 96, "α1"},
		{NamesHash, 0, "#a"}, {NamesHash, 1, "b"}, {NamesHash, 3, "#d"},
		{NamesSeparators, 0, "a,x"}, {NamesSeparators, 1, "b x"}, {NamesSeparators, 2, "c\tx"}, {NamesSeparators, 3, "d\r"},
	}
	for _, ex := range examples {
		if got := ex.style.itemName(ex.i); got != ex.expected {
			t.Errorf("style %d item %d: name %q, want %q", ex.style, ex.i, got, ex.expected)
		}
	}

	for style := NamesLetters; style <= NamesSeparators; style++ {
		seen := map[string]int{}
		for i := range 1000 {
			name := style.itemName(i)
			if j, dup := seen[name]; dup {
				t.Fatalf("style %d: items %d and %d share the name %q", style, j, i, name)
			}
			seen[name] = i
			if SafeName(name) != style.RoundTrips() {
				t.Fatalf("style %d: SafeName(%q) = %v, RoundTrips() = %v", style, name, SafeName(name), style.RoundTrips())
			}
		}
	}
}

func TestSafeName(t *testing.T) {
	t.Parallel()
	for name, expected := range map[string]bool{
		"a": true, "#a": true, "a#": true, "café": true, "\xff\xfe": true, "(3)": true,
		strings1024(): true, strings1024() + "x": false,
		"": false, "a b": false, "a,b": false, "a\tb": false, "a\r": false, "a\nb": false, "a\x00b": false,
	} {
		if got := SafeName(name); got != expected {
			t.Errorf("SafeName(%q) = %v, want %v", name, got, expected)
		}
	}
}

// strings1024 returns a name of exactly 1024 bytes.
func strings1024() string {
	return string(bytes.Repeat([]byte("n"), 1024))
}

func TestRNG(t *testing.T) {
	t.Parallel()
	for _, n := range []uint64{1, 2, 3, 7, 1 << 40, 1<<63 + 1} {
		r := &rng{src: newTestPCG(n)}
		for range 1000 {
			if v := r.uint64N(n); v >= n {
				t.Fatalf("uint64N(%d) = %d", n, v)
			}
			if f := r.float(); f < 0 || f >= 1 {
				t.Fatalf("float() = %v", f)
			}
		}
	}
	// A small modulus hits every value.
	r := &rng{src: newTestPCG(1)}
	counts := make([]int, 5)
	for range 5000 {
		counts[r.intN(5)]++
	}
	for v, c := range counts {
		if c < 800 || c > 1200 {
			t.Errorf("intN(5) returned %d %d times in 5000 draws", v, c)
		}
	}
	perm := []int{0, 1, 2, 3, 4, 5}
	r.shuffle(len(perm), func(i, j int) { perm[i], perm[j] = perm[j], perm[i] })
	if slices.Sort(perm); !slices.Equal(perm, []int{0, 1, 2, 3, 4, 5}) {
		t.Errorf("shuffle lost elements: %v", perm)
	}
}

// newTestPCG returns a PCG source for rng tests.
func newTestPCG(seed uint64) *rand.PCG {
	return rand.NewPCG(seed, 0)
}

// ExampleGenerate shows a reproducible random dataset in upstream's
// format.
func ExampleGenerate() {
	txs, err := Generate(GenConfig{Seed: 1, NumTransactions: 4, NumItems: 4, MinLen: 1, MaxLen: 3, EmptyProb: 0.2})
	if err != nil {
		panic(err)
	}
	var buf bytes.Buffer
	if err := WriteTable(&buf, txs, false); err != nil {
		panic(err)
	}
	fmt.Print(buf.String())
	// Output:
	// d
	// b c
	//
	// d a
}
