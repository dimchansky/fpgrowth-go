// TestUpdateScripts regenerates the simulated scripts under testdata and
// the reviewed Go outputs (<name>.go.out) of scripts that declare a
// deviation. It only runs with REPORT_UPDATE=1:
//
//	REPORT_UPDATE=1 go test ./internal/report -run TestUpdateScripts
//	reference/harness/report/gen.sh BUILD_DIR   # C outputs (*.c.out)
//
// Review the .go.out diffs against the .c.out files before committing.
func TestUpdateScripts(t *testing.T) {
	if os.Getenv("REPORT_UPDATE") == "" {
		t.Skip("set REPORT_UPDATE=1 to regenerate the testdata scripts")
	}
	writeRandomScripts(t)
	writeNamedScripts(t)
	writeDeviationOutputs(t)
}

const scriptHeader = "# Generated by TestUpdateScripts (internal/report/report_gen_test.go).\n"

func writeScript(t *testing.T, path, comment, script string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	text := scriptHeader + comment + script
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
}

// randomScriptConfig draws the configuration of random script i. It
// avoids the documented deviations (fast-mode empty set, count-only zmax
// for closed/maximal, maximal top-level perfect extensions), which are
// covered by the named scenarios.
func randomScriptConfig(rng *rand.Rand, i int, db *simDB) *simConfig {
	kinds := []Target{TargetAll, TargetClosed, TargetMaximal, TargetGenerators, TargetAll, TargetRules}
	target := kinds[i%len(kinds)]
	cfg := randomSimConfig(rng, db, target)
	cfg.queries = true
	switch i % len(kinds) {
	case 4: // istree item set reporting
		cfg.istree = true
		cfg.target = []Target{TargetAll, TargetClosed, TargetMaximal}[rng.IntN(3)]
		cfg.mode = ModeNoFilter
		cfg.eval = false
	case 5: // istree rule reporting
		cfg.rules = true
		cfg.mode = ModeNoFilter
		cfg.eval = false
		cfg.border = nil
	}
	switch rng.IntN(5) {
	case 0:
		if cfg.zmax >= MaxSize || cfg.target&(TargetClosed|TargetMaximal) == 0 {
			cfg.output = "count"
		}
	case 1:
		if cfg.zmin != 1 {
			cfg.output = "file"
		}
	}
	return cfg
}

// maximalPexOnly reports whether db and cfg trigger the deviation for
// maximal sets consisting of top-level perfect extensions only.
func maximalPexOnly(db *simDB, cfg *simConfig) bool {
	if cfg.target != TargetMaximal || !cfg.perfect || cfg.istree || cfg.rules {
		return false
	}
	total := db.total()
	pex := false
	for _, f := range db.itemFreqs() {
		switch {
		case f < cfg.smin:
		case f >= total:
			pex = true
		default:
			return false
		}
	}
	return pex && cfg.smin <= total
}

func writeRandomScripts(t *testing.T) {
	t.Helper()
	const n = 60
	for i := range n {
		seed := uint64(1000 + i)
		rng := rand.New(rand.NewPCG(seed, 7))
		var db *simDB
		var cfg *simConfig
		for {
			db = randomDB(rng, 3+rng.IntN(6), 3+rng.IntN(8), 1+rng.IntN(3), 0.3+rng.Float64()/2)
			cfg = randomScriptConfig(rng, i, db)
			if !maximalPexOnly(db, cfg) {
				break
			}
		}
		_, script, err := simulate(db, cfg, &collectSink{}, rng, true)
		if err != nil {
			t.Fatal(err)
		}
		comment := fmt.Sprintf("# Random script %d (seed %d): %s target, output %s.\n# Database: %v weights %v\n",
			i, seed, targetName(cfg.target), cfg.output, db.trans, db.wgts)
		writeScript(t, filepath.Join("testdata", "random", fmt.Sprintf("r%03d.isr", i)), comment, script)
	}
}

// namedDB returns small databases from the upstream audit.
func namedDB(name string) *simDB {
	parse := func(lines ...string) *simDB {
		db := &simDB{}
		for _, l := range lines {
			var tr []tract.Item
			for _, f := range strings.Fields(l) {
				it := tract.Item(f[0] - 'a')
				tr = append(tr, it)
				db.nItems = max(db.nItems, int(it)+1)
			}
			sortItemsAsc(tr)
			db.trans = append(db.trans, tr)
			db.wgts = append(db.wgts, 1)
		}
		return db
	}
	switch name {
	case "test1": // fpgrowth/ex/test1.tab
		return parse("a b c", "a d e", "b c d", "a b c d", "b c", "a b d", "d e", "a b c d", "c d e", "a b c")
	case "pexo": // report.md appendix A (x=d, y=e)
		return parse("d a b c", "d a b c", "e d", "e")
	case "allA": // report.md appendix A
		return parse("a b", "a c", "a b c")
	case "ab2": // maximal deviation: only top-level perfect extensions
		return parse("a b", "a b")
	case "mp": // fpgrowth-core.md B4 reproducer
		return parse("a", "a b", "a c", "a")
	}
	panic("unknown database " + name)
}

func sortItemsAsc(items []tract.Item) { sortItems(items, 1) }

type namedScenario struct {
	name, db, comment string
	cfg               simConfig
	deviation         string // documented deviation exercised, if any
}

