#!/usr/bin/env bash
#
# Regenerate internal/cconv/testdata/expected.txt from the corpus with the
# platform C library. See README.md in this directory.
#
# Usage: ./gen.sh BUILD_DIR
#
# BUILD_DIR receives the compiled harness (any scratch directory outside
# the repository). The expected-results file is rewritten in place.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 BUILD_DIR" >&2; exit 2; }
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
build=$1
mkdir -p "$build"

cc=${CC:-cc}
$cc -std=c99 -O1 -Wall -Wextra -o "$build/cconvdump" "$here/cconvdump.c"

corpus=$root/internal/cconv/testdata/corpus.txt
out=$root/internal/cconv/testdata/expected.txt
{
	echo "# Generated by reference/harness/cconv/gen.sh -- do not edit."
	echo "# Platform: $(uname -s) $(uname -r) $(uname -m)"
	echo "# Compiler: $($cc --version 2>/dev/null | head -n 1)"
	"$build/cconvdump" "$corpus"
} >"$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out" >&2
