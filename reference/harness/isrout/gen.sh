#!/usr/bin/env bash
#
# Regenerate the golden files of internal/isrout/testdata from the pristine
# upstream C sources. See README.md in this directory.
#
# Usage: ./gen.sh BUILD_DIR [FPGROWTH]
#
# BUILD_DIR receives the object files and the numdump harness (any scratch
# directory outside the repository). FPGROWTH is the reference executable
# (default: reference/build/release/fpgrowth/src/fpgrowth, built by
# reference/build.sh release).
#
# Environment: CC (default: cc).
set -euo pipefail

[ $# -ge 1 ] && [ $# -le 2 ] || { echo "usage: $0 BUILD_DIR [FPGROWTH]" >&2; exit 2; }
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
src=$root/reference/upstream/fpgrowth-6.21
td=$root/internal/isrout/testdata
build=$1
fpg=${2:-$root/reference/build/release/fpgrowth/src/fpgrowth}
mkdir -p "$build"
[ -x "$fpg" ] || { echo "gen.sh: $fpg not found (run reference/build.sh release)" >&2; exit 1; }

cc=${CC:-cc}
case " $cc " in
*" -std="*) ;;
*) cc="$cc -std=c99" ;;
esac

# --- numdump: isr_numout() corpus -------------------------------------

# Upstream release flags (tract/src/makefile, util/src/makefile) plus
# -ffp-contract=off like every oracle build (reference/build.sh).
cflags=(-Wall -Wextra -Wno-unused-parameter -Wconversion -pedantic
	-DNDEBUG -O3 -funroll-loops -ffp-contract=off)
incs=(-I"$src/tract/src" -I"$src/util/src" -I"$src/math/src")
log=$build/build.log
: >"$log"
compile() { # compile <object> <source> [defines...]
	local obj=$1 file=$2
	shift 2
	$cc "${cflags[@]}" "${incs[@]}" "$@" -c "$file" -o "$build/$obj" 2>>"$log" ||
		{ cat "$log" >&2; exit 1; }
}

# The objects fpgrowth links for the reporter, with the defines of their
# makefile rules (repcm.o = report.c with ISR_PATSPEC and ISR_CLOMAX).
compile repcm.o    "$src/tract/src/report.c" -DISR_PATSPEC -DISR_CLOMAX
compile clomax.o   "$src/tract/src/clomax.c"
compile patspec.o  "$src/tract/src/patspec.c" -DPSP_REPORT
compile taread.o   "$src/tract/src/tract.c" -DTA_READ
compile arrays.o   "$src/util/src/arrays.c"
compile memsys.o   "$src/util/src/memsys.c"
compile idmap.o    "$src/util/src/symtab.c" -DIDMAPFN
compile escape.o   "$src/util/src/escape.c"
compile tabread.o  "$src/util/src/tabread.c"
compile tabwrite.o "$src/util/src/tabwrite.c"
compile scform.o   "$src/util/src/scanner.c"
compile numdump.o  "$here/numdump.c" -DISR_PATSPEC -DISR_CLOMAX

objs=(numdump.o repcm.o clomax.o patspec.o taread.o arrays.o memsys.o
	idmap.o escape.o tabread.o tabwrite.o scform.o)
(cd "$build" && $cc -o numdump "${objs[@]}" -lm)
echo "built $build/numdump" >&2

header() {
	echo "# Generated by reference/harness/isrout/gen.sh -- do not edit."
	echo "# Platform: $(uname -s) $(uname -r) $(uname -m)"
	echo "# Compiler: $($cc --version 2>/dev/null | head -n 1) (-O3 -ffp-contract=off)"
}
{ header; "$build/numdump" corpus; } >"$td/numout.txt.tmp"
mv "$td/numout.txt.tmp" "$td/numout.txt"
{ header; "$build/numdump" gfmt; } >"$td/gfmt.txt.tmp"
mv "$td/gfmt.txt.tmp" "$td/gfmt.txt"
echo "wrote $td/numout.txt $td/gfmt.txt" >&2

# --- golden CLI outputs -----------------------------------------------

# For every case of golden/cases.txt:
#   NAME.c.out  output of the case's arguments
#   NAME.m.out  the same mining options with a machine-readable format
#   NAME.z      stdout (-Z statistics) of the machine-readable run
#   NAME.psp    pattern spectrum (-P) of the machine-readable run (sets)
gd=$td/golden
setfmt=' # %a %17w %17e %Q'
rulefmt=' # %a %b %h %17e %Q'
ncases=0
run_case() {
	local name=$1 input=$2
	shift 2
	local mine=() a rules=0
	for a in "$@"; do
		case $a in
		-v* | -k* | -I* | -h* | -g) ;;
		-tr) rules=1; mine+=("$a") ;;
		*) mine+=("$a") ;;
		esac
	done
	(
		cd "$gd"
		"$fpg" "$@" "$input" "$name.c.out" 2>/dev/null
		if [ $rules -eq 1 ]; then
			"$fpg" ${mine[@]+"${mine[@]}"} -k'|' -I' => ' -v"$rulefmt" -Z \
				"$input" "$name.m.out" >"$name.z" 2>/dev/null
			rm -f "$name.psp"
		else
			"$fpg" ${mine[@]+"${mine[@]}"} -k'|' -v"$setfmt" -Z -P"$name.psp" \
				"$input" "$name.m.out" >"$name.z" 2>/dev/null
		fi
	)
	ncases=$((ncases + 1))
}

name='' input='' args=()
while IFS= read -r line || [ -n "$line" ]; do
	case $line in
	'case '*)
		[ -z "$name" ] || run_case "$name" "$input" ${args[@]+"${args[@]}"}
		set -- $line
		name=$2 input=$3 args=()
		;;
	'arg '*) args+=("${line#arg }") ;;
	esac
done <"$gd/cases.txt"
[ -z "$name" ] || run_case "$name" "$input" ${args[@]+"${args[@]}"}
echo "generated $ncases golden case(s) in $gd" >&2
