#!/usr/bin/env bash
#
# Regenerate internal/ruleval/testdata/{measures,specfun}_c.txt from the
# pristine upstream ruleval.c, gamma.c and chi2.c. See README.md in this
# directory.
#
# Usage: ./gen.sh BUILD_DIR
#
# BUILD_DIR receives the object files and the harness executable (any
# scratch directory outside the repository). The fixtures are rewritten
# in place.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 BUILD_DIR" >&2; exit 2; }
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
up=$root/reference/upstream
src=$up/fpgrowth-6.21
out=$root/internal/ruleval/testdata
build=$1
mkdir -p "$build" "$out"

# The upstream sources must be pristine (same manifest as reference/build.sh).
if command -v sha256sum >/dev/null 2>&1; then sha=(sha256sum); else sha=(shasum -a 256); fi
(cd "$up" && grep -E 'math/src/(ruleval|gamma|chi2)\.[ch]$|tract/src/tract\.h$' SHA256SUMS |
	"${sha[@]}" -c --quiet -) || { echo "upstream sources are not pristine" >&2; exit 1; }

cc=${CC:-cc}
# Upstream release flags (math/src/makefile) plus -ffp-contract=off, like the
# oracle variants of reference/build.sh: no fused multiply-add.
cflags="-std=c99 -O3 -funroll-loops -DNDEBUG -ffp-contract=off"
incs="-I$src/math/src -I$src/tract/src -I$src/util/src"
for f in gamma chi2 ruleval; do
	# shellcheck disable=SC2086
	$cc $cflags $incs -c "$src/math/src/$f.c" -o "$build/$f.o"
done
# shellcheck disable=SC2086
$cc $cflags $incs -c "$here/harness.c" -o "$build/harness.o"
$cc -o "$build/harness" "$build/harness.o" "$build/ruleval.o" "$build/chi2.o" "$build/gamma.o" -lm

# On arm64, check that no fused multiply-add instruction was emitted.
if [ "$(uname -m)" = arm64 ] || [ "$(uname -m)" = aarch64 ]; then
	if command -v otool >/dev/null 2>&1; then dis=(otool -tv); else dis=(objdump -d); fi
	for f in gamma chi2 ruleval; do
		n=$("${dis[@]}" "$build/$f.o" | grep -cE '\s(fmadd|fmsub|fnmadd|fnmsub)\s' || true)
		[ "$n" -eq 0 ] || { echo "$f.o contains $n fused multiply-add instructions" >&2; exit 1; }
	done
fi

header() {
	echo "# Generated by reference/harness/ruleval/gen.sh -- do not edit."
	echo "# Upstream: fpgrowth-6.21 math/src/ruleval.c gamma.c chi2.c (pristine)"
	echo "# Platform: $(uname -s) $(uname -r) $(uname -m)"
	echo "# Compiler: $($cc --version 2>/dev/null | head -n 1)"
	echo "# Flags: $cflags"
}
for mode in measures specfun; do
	{
		header
		"$build/harness" $mode
	} >"$out/${mode}_c.txt.tmp"
	mv "$out/${mode}_c.txt.tmp" "$out/${mode}_c.txt"
	echo "wrote $out/${mode}_c.txt ($(wc -c <"$out/${mode}_c.txt") bytes)" >&2
done
