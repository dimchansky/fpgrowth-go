#!/usr/bin/env bash
#
# Regenerate the golden files of internal/tabread from upstream's C reader.
# See README.md in this directory.
#
# Usage: ./gen.sh BUILD_DIR
#
# BUILD_DIR receives the compiled harness (any scratch directory outside
# the repository). Writes internal/tabread/testdata/golden.txt and
# internal/tabread/testdata/escapes.golden.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 BUILD_DIR" >&2; exit 2; }
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
src=$root/reference/upstream/fpgrowth-6.21
td=$root/internal/tabread/testdata
build=$1
mkdir -p "$build"
build=$(cd "$build" && pwd)

cc=${CC:-cc}
cflags=(-std=c99 -O1 -g -Wall -Wno-unused-parameter -I"$src/util/src" -I"$src/tract/src")

# Upstream objects, compiled like the upstream makefiles do (taread.o is
# tract.c with TA_READ, idmap.o is symtab.c with IDMAPFN), but with
# assertions enabled.
$cc "${cflags[@]}" -c "$src/util/src/arrays.c" -o "$build/arrays.o"
$cc "${cflags[@]}" -c "$src/util/src/memsys.c" -o "$build/memsys.o"
$cc "${cflags[@]}" -DIDMAPFN -c "$src/util/src/symtab.c" -o "$build/idmap.o"
$cc "${cflags[@]}" -c "$src/util/src/escape.c" -o "$build/escape.o"
$cc "${cflags[@]}" -c "$src/util/src/tabread.c" -o "$build/tabread.o"
$cc "${cflags[@]}" -DTA_READ -c "$src/tract/src/tract.c" -o "$build/taread.o"
$cc "${cflags[@]}" -DTA_READ -c "$here/tabdump.c" -o "$build/tabdump.o"
$cc "${cflags[@]}" -c "$here/escdump.c" -o "$build/escdump.o"
$cc -o "$build/tabdump" "$build/tabdump.o" "$build/taread.o" "$build/tabread.o" \
	"$build/escape.o" "$build/idmap.o" "$build/arrays.o" "$build/memsys.o" -lm
$cc -o "$build/escdump" "$build/escdump.o" "$build/escape.o"

header() {
	echo "# Generated by reference/harness/tabread/gen.sh -- do not edit."
	echo "# Platform: $(uname -s) $(uname -r) $(uname -m)"
	echo "# Compiler: $($cc --version 2>/dev/null | head -n 1)"
}

# Escape decoding.
{
	header
	"$build/escdump" "$td/escapes.txt"
} >"$td/escapes.golden.tmp"
mv "$td/escapes.golden.tmp" "$td/escapes.golden"

# Reader cases. Run from the testdata directory so that file names in
# messages are the relative names of the manifest.
set -f # option values may contain glob characters
cd "$td"
{
	header
	while read -r name mode file rest; do
		case $name in '' | '#'*) continue ;; esac
		args=()
		fargs=()
		for tok in $rest; do
			[ "$tok" = "''" ] && tok=
			args+=("$tok")
			[ "$tok" = -w ] || fargs+=("$tok")
		done
		echo "=== $name $mode"
		"$build/tabdump" "$mode" ${args[@]+"${args[@]}"} "$file"
		echo "=== $name fields"
		"$build/tabdump" fields ${fargs[@]+"${fargs[@]}"} "$file"
	done <cases.txt
} >golden.txt.tmp
mv golden.txt.tmp golden.txt
echo "wrote $td/golden.txt and $td/escapes.golden" >&2
